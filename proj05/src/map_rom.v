`default_nettype none

// =====================================================================
// MAP ROM  (= "Name Table" ใน NES)
// ---------------------------------------------------------------------
// เก็บว่า "ช่องไหนของแผนที่ ใช้ tile เบอร์อะไร"
//   - แผนที่กว้าง 80 ช่อง x สูง 30 ช่อง  (1 ช่อง = 16x16 pixel)
//   - 80*16 = 1280 px  -> กว้างเป็น 2 เท่าของจอ (640) จึงเลื่อนได้
//   - 30*16 =  480 px  -> สูงเท่าจอพอดี
//   - มี 2 ชั้น (layer) เก็บต่อกันในไฟล์เดียว:
//         layer 0 = แถว  0-29 ในไฟล์ = ชั้นหลัง (ฟ้า เมฆ ทะเล)
//         layer 1 = แถว 30-59 ในไฟล์ = ชั้นหน้า (ต้นมะพร้าว ชายหาด)
//   - แต่ละช่องเก็บเลข tile 8 bit (0-255)   tile 0 = ว่าง (โปร่งใส)
//   ไฟล์ beach_map.mem สร้างจาก png2tiles.py
// =====================================================================
module map_rom (
    input  wire       layer,    // 0 = ชั้นหลัง, 1 = ชั้นหน้า
    input  wire [6:0] col,      // คอลัมน์ของช่อง 0..79
    input  wire [4:0] row,      // แถวของช่อง    0..29
    output wire [7:0] tile_id   // เลข tile ที่อยู่ในช่องนั้น
);
  reg [7:0] mem [0:80*60-1];    // 2 ชั้น x 2400 ช่อง

  initial $readmemh("../data/beach_map.mem", mem);

  // ชั้นหน้าอยู่ถัดลงไป 30 แถว:  index = (layer*30 + row) * 80 + col
  assign tile_id = mem[(layer * 30 + row) * 80 + col];
endmodule
