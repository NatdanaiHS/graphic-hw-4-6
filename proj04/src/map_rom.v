`default_nettype none

// =====================================================================
// MAP ROM  (= "Name Table" ใน NES)
// ---------------------------------------------------------------------
// เก็บว่า "ช่องไหนของแผนที่ ใช้ tile เบอร์อะไร"
//   - แผนที่กว้าง 80 ช่อง x สูง 30 ช่อง  (1 ช่อง = 16x16 pixel)
//   - 80*16 = 1280 px  -> กว้างเป็น 2 เท่าของจอ (640) จึงเลื่อนได้
//   - 30*16 =  480 px  -> สูงเท่าจอพอดี
//   - แต่ละช่องเก็บเลข tile 8 bit (0-255)   tile 0 = ท้องฟ้า (ว่าง)
// =====================================================================
module map_rom (
    input  wire [6:0] col,      // คอลัมน์ของช่อง 0..79
    input  wire [4:0] row,      // แถวของช่อง    0..29
    output wire [7:0] tile_id   // เลข tile ที่อยู่ในช่องนั้น
);
  reg [7:0] mem [0:80*30-1];    // 2400 ช่อง

  initial $readmemh("../data/map2.mem", mem);

  // แปลง (row, col) เป็นเลขช่องเรียงแถว: index = row * 80 + col
  assign tile_id = mem[row * 80 + col];
endmodule
